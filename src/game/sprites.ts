// Byte layouts and addresses: docs/space-invaders-1978.md.
// Each byte is a vertical column, rotated into the upright arcade screen.
const sprite = (columns: number[], height = 8): string[] =>
    Array.from({ length: height }, (_, y) =>
        columns
            .map(column => (column & (1 << (height - 1 - y)) ? "X" : "."))
            .join("")
    );

